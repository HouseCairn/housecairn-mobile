"""Keeps the rules the app carries from the web application aligned with it.

The app is standalone, but it carries rules of the web application
(HouseCairn/housecairn): the recurrence and seasons, the library of task templates and
the design tokens. `tool/web_alignment.json` says on which release and commit of the web
application each of them was last aligned. This script compares, or moves, that pin:

    python3 tool/web_alignment.py check --web <clone of HouseCairn/housecairn>
    python3 tool/web_alignment.py update --web <clone> --release vX.Y.Z [--report <file>]

`check` regenerates every element from its pinned commit and compares it with the file
the app carries: the recurrence vectors and the task templates byte for byte, the design
tokens value by value (every web token is in `design/tokens.json` with the same value;
the app may add its own). It fails on any difference. CI runs it on every pull request.

`update` regenerates, at the release given, the files that follow mechanically (vectors,
templates, tokens) and writes a Markdown report of what changed on the web and in the app, with
the web files cited by docs/spec.md that changed and need a reading. Only when one of those files
would differ does it write them, move the pin of every element to the release and print
`changed=true`. A release that changes none of them (a refactoring, another part of the web) is
"checked, nothing to port": nothing is written, the pin stays on the last release that mattered
(`check` compares each element with its own pinned commit) and it prints `changed=false`. The
source header of the vectors, which names the commit, is not a difference by itself. It never
changes Dart code: when a rule of the web changed, the regenerated vectors make `flutter test`
fail, and that is the signal.

    python3 tool/web_alignment.py verify-patch <file>   # a patch limited to ALLOWED_PATHS
    python3 tool/web_alignment.py allowed-paths

Requirements: Python 3.11 or later, git, and uv (https://docs.astral.sh/uv/) on PATH, or
its path in $UV. The recurrence vectors are generated by tool/recurrence_vectors.py in an
isolated environment of the web application at the pinned commit (`uv sync --frozen
--no-dev`, with the Python version of the pin), so the same commit gives the same file.
The clone needs the tags and the pinned commits; `git clone
https://github.com/HouseCairn/housecairn` is enough. Nothing is written to the clone but
a temporary worktree, removed at the end.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = ROOT / "tool" / "web_alignment.json"
GENERATOR = ROOT / "tool" / "recurrence_vectors.py"
SPEC = ROOT / "docs" / "spec.md"
WEB_REPOSITORY = "HouseCairn/housecairn"
ELEMENTS = ("recurrence", "task_templates", "design_tokens")
RELEASE = re.compile(r"^v\d+\.\d+\.\d+$")
COMMIT = re.compile(r"^[0-9a-f]{40}$")


class AlignmentError(Exception):
    pass


def git(web: Path, *args: str) -> bytes:
    result = subprocess.run(["git", "-C", str(web), *args], capture_output=True)
    if result.returncode != 0:
        raise AlignmentError(f"git {' '.join(args)}: {result.stderr.decode(errors='replace').strip()}")
    return result.stdout


def resolve(web: Path, release: str) -> str:
    """The commit of a release tag of the web repository."""
    if not RELEASE.match(release):
        raise AlignmentError(f"not a release tag: {release!r} (expected vX.Y.Z)")
    return git(web, "rev-parse", "--verify", "--quiet", f"refs/tags/{release}^{{commit}}").decode().strip()


def show(web: Path, commit: str, path: str) -> bytes:
    return git(web, "show", f"{commit}:{path}")


def load_reference() -> dict:
    if not REFERENCE.exists():
        raise AlignmentError(f"{REFERENCE.relative_to(ROOT)} is missing: the pin of the web release is required")
    reference = json.loads(REFERENCE.read_text(encoding="utf-8"))
    if reference.get("repository") != WEB_REPOSITORY:
        raise AlignmentError(f"{REFERENCE.name}: repository must be {WEB_REPOSITORY}")
    for name in ELEMENTS:
        element = reference["elements"].get(name)
        if element is None:
            raise AlignmentError(f"{REFERENCE.name}: no pin for {name}")
        if not RELEASE.match(element.get("release", "")) or not COMMIT.match(element.get("commit", "")):
            raise AlignmentError(f"{REFERENCE.name}: {name} needs a release vX.Y.Z and a full commit")
    if set(reference["elements"]) != set(ELEMENTS):
        raise AlignmentError(f"{REFERENCE.name}: the elements are exactly {', '.join(ELEMENTS)}")
    return reference


def write_reference(reference: dict) -> None:
    REFERENCE.write_text(json.dumps(reference, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


# Recurrence: vectors generated from the Python module of the pinned commit.


def recurrence_vectors(web: Path, commit: str, python: str) -> bytes:
    uv = os.environ.get("UV", "uv")
    env = {k: v for k, v in os.environ.items() if k not in ("VIRTUAL_ENV", "PYTHONPATH")}
    env["UV_PYTHON_PREFERENCE"] = "only-managed"
    with tempfile.TemporaryDirectory(prefix="web-alignment-") as tmp:
        tree = Path(tmp) / "web"
        git(web, "worktree", "add", "--detach", "--quiet", str(tree), commit)
        try:
            for command in (
                [uv, "sync", "--frozen", "--no-dev", "--quiet", "--python", python],
                [uv, "run", "--frozen", "--no-dev", "--no-sync", "python", "-I", str(GENERATOR),
                 "--source-commit", commit, str(Path(tmp) / "vectors.json")],
            ):
                result = subprocess.run(command, cwd=tree, env=env, capture_output=True, text=True)
                if result.returncode != 0:
                    raise AlignmentError(f"{' '.join(command[:2])} at {commit[:7]}: {result.stderr.strip()}")
            return (Path(tmp) / "vectors.json").read_bytes()
        finally:
            git(web, "worktree", "remove", "--force", str(tree))


def vectors_changed(old: bytes, new: bytes) -> int:
    """Number of vector lines that differ, the header line of the source left out."""
    def lines(data: bytes) -> list[str]:
        return [l for l in data.decode().splitlines() if not l.lstrip().startswith('"source"')]
    a, b = lines(old), lines(new)
    return sum(1 for x, y in zip(a, b) if x != y) + abs(len(a) - len(b))


# Design tokens: every web token, with its value, in the tokens of the app.


def token_groups(document: dict) -> dict[str, dict]:
    return {k: v for k, v in document.items() if not k.startswith("$") and isinstance(v, dict)}


def token_differences(mobile: dict, web: dict) -> list[str]:
    differences = []
    for group, values in token_groups(web).items():
        carried = mobile.get(group)
        for key, value in values.items():
            if not isinstance(carried, dict) or key not in carried:
                differences.append(f"{group}.{key}: missing in the app (web: {value})")
            elif carried[key] != value:
                differences.append(f"{group}.{key}: {carried[key]} in the app, {value} on the web")
    return differences


def merge_tokens(mobile: dict, web: dict, old_web: dict) -> tuple[dict, list[str]]:
    """The tokens of the app with the values of the web; what the web removed is kept and listed."""
    notes = token_differences(mobile, web)
    for group, values in token_groups(web).items():
        mobile.setdefault(group, {}).update(values)
    for group, values in token_groups(old_web).items():
        for key in values:
            if key not in token_groups(web).get(group, {}):
                notes.append(f"{group}.{key}: removed on the web, still in the app (remove it by hand)")
    return mobile, notes


def dump_tokens(document: dict) -> bytes:
    return (json.dumps(document, indent=2, ensure_ascii=False) + "\n").encode()


# Files of the web cited by docs/spec.md, which no script ports: a change needs a reading.


def spec_sources(web: Path, commit: str) -> list[str]:
    text = SPEC.read_text(encoding="utf-8")
    paths = set()
    for path in re.findall(r"`([a-z_]+(?:/[a-z_]+)*\.(?:py|yaml))(?::[0-9, :-]+)?`", text):
        paths.add(f"src/housecairn/{path}")
    adrs = set(re.findall(r"web ADR (\d{4})|ADR (\d{4}) of the web", text))
    numbers = {a or b for a, b in adrs}
    for path in git(web, "ls-tree", "-r", "--name-only", commit, "--", "docs/adr").decode().split():
        if Path(path).name[:4] in numbers:
            paths.add(path)
    return sorted(paths)


def spec_commit() -> str | None:
    match = re.search(r"`main` at commit `([0-9a-f]{7,40})`", SPEC.read_text(encoding="utf-8"))
    return match.group(1) if match else None


def changed_files(web: Path, old: str, new: str, paths: list[str]) -> list[str]:
    if not paths or old == new:
        return []
    return git(web, "diff", "--name-only", old, new, "--", *paths).decode().split()


# Commands.


def check(web: Path) -> int:
    reference = load_reference()
    failures: list[str] = []
    for name in ELEMENTS:
        before = len(failures)
        element = reference["elements"][name]
        tag_commit = resolve(web, element["release"])
        if tag_commit != element["commit"]:
            failures.append(f"{name}: {element['release']} is {tag_commit}, the pin says {element['commit']}")
            continue
        commit = element["commit"]
        if name == "recurrence":
            expected = recurrence_vectors(web, commit, element["python"])
            carried = (ROOT / element["mobile"][0]).read_bytes()
            if expected != carried:
                count = vectors_changed(expected, carried)
                what = f"{count} vector lines differ" if count else "only the source header differs"
                failures.append(
                    f"recurrence: {element['mobile'][0]} is not the file generated at {element['release']} "
                    f"({what}); regenerate it, never edit it"
                )
        elif name == "task_templates":
            expected = show(web, commit, element["web"][0])
            carried_file = ROOT / element["mobile"][0]
            if not carried_file.exists() or expected != carried_file.read_bytes():
                failures.append(f"task_templates: {element['mobile'][0]} is not {element['web'][0]} of {element['release']}")
        else:
            web_tokens = json.loads(show(web, commit, element["web"][0]))
            mobile_tokens = json.loads((ROOT / element["mobile"][0]).read_text(encoding="utf-8"))
            failures += [f"design_tokens: {d}" for d in token_differences(mobile_tokens, web_tokens)]
        print(f"{name}: {element['release']} ({commit[:7]}): {'same' if len(failures) == before else 'DIFFERENT'}")
    for failure in failures:
        print(f"::error::{failure}" if os.environ.get("GITHUB_ACTIONS") else f"FAIL {failure}")
    if failures:
        print("The app no longer carries what tool/web_alignment.json pins. Run `update` (CONTRIBUTING.md).")
        return 1
    print("Every element is what its pinned web release gives.")
    return 0


def update(web: Path, release: str, report_path: Path | None) -> int:
    reference = load_reference()
    commit = resolve(web, release)
    results = []
    for name in ELEMENTS:
        element = reference["elements"][name]
        old = element["commit"]
        web_changed = changed_files(web, old, commit, element["web"])
        notes: list[str] = []
        mobile_file = ROOT / element["mobile"][0]
        before = mobile_file.read_bytes() if mobile_file.exists() else b""
        header_only = False
        if name == "recurrence":
            after = recurrence_vectors(web, commit, element["python"])
            if before and before != after:
                count = vectors_changed(before, after)
                header_only = count == 0
                notes.append(f"{count} vector lines changed" if count else "source header only, every vector unchanged")
        elif name == "task_templates":
            after = show(web, commit, element["web"][0])
        else:
            merged, notes = merge_tokens(
                json.loads(before), json.loads(show(web, commit, element["web"][0])),
                json.loads(show(web, old, element["web"][0])),
            )
            after = dump_tokens(merged)
        results.append((name, element, old, web_changed, notes, mobile_file, before, after, header_only))

    # The app differs only when a file it carries would change. A new commit of the web whose
    # vectors, templates and tokens are the same is not a gap: nothing is written, no pull request
    # is opened, and the pin stays where it is (`check` compares each element with its own pinned
    # commit, so the app stays consistent). The source header of the vectors, which names the
    # commit, does not count by itself.
    changed = any(after != before and not header_only for *_, before, after, header_only in results)
    if changed:
        lines = [f"Web release: [{release}](https://github.com/{WEB_REPOSITORY}/releases/tag/{release}) (`{commit}`).", ""]
    else:
        pins = ", ".join(sorted({e["release"] for e in reference["elements"].values()}))
        lines = [
            f"Web release {release} (`{commit}`) checked, nothing to port: no file the app carries differs.",
            f"The pin stays at {pins}; it moves with the next release that changes a ported file.",
            "",
        ]
    for name, element, old, web_changed, notes, mobile_file, before, after, header_only in results:
        if changed:
            moved = f"{element['release']} → {release}" if old != commit else f"{release}, unchanged"
            if after != before:
                mobile_file.parent.mkdir(parents=True, exist_ok=True)
                mobile_file.write_bytes(after)
            if after == before:
                state = "regenerated, identical"
            else:
                state = "regenerated, source header only" if header_only else "regenerated, changed"
            lines.append(f"- **{name}** ({moved}): `{element['mobile'][0]}` {state}.")
            element["release"], element["commit"] = release, commit
        else:
            lines.append(f"- **{name}** (pinned {element['release']}): `{element['mobile'][0]}` no difference at {release}.")
        for path in web_changed:
            lines.append(f"  - web file changed: `{path}`")
        for note in notes:
            lines.append(f"  - {note}")
    if changed:
        write_reference(reference)
    since = spec_commit()
    if since:
        cited = changed_files(web, git(web, "rev-parse", since).decode().strip(), commit, spec_sources(web, commit))
        lines += ["", f"Web files cited by `docs/spec.md` (written at `{since}`) that changed since:"]
        lines += [f"- `{p}`" for p in cited] or ["- none"]
    report = "\n".join(lines) + "\n"
    print(report, end="")
    if report_path:
        report_path.write_text(report, encoding="utf-8")
    print(f"changed={'true' if changed else 'false'}")
    return 0


# The only files a run of `update` may change. The workflow applies its patch with the token of the
# project's GitHub App, and `update` runs code of the web application: any other path is refused.

ALLOWED_PATHS = (
    "test/fixtures/recurrence_vectors.json",
    "assets/task_templates.yaml",
    "design/tokens.json",
    "tool/web_alignment.json",
)
HEADER_REFUSED = ("old mode", "new mode", "deleted file mode", "rename ", "copy ", "similarity ", "dissimilarity ")


def patch_problems(patch: bytes) -> list[str]:
    """What is wrong with a patch made by `git diff --cached --binary`; empty when it is acceptable."""
    with tempfile.TemporaryDirectory(prefix="web-alignment-patch-") as tmp:
        file = Path(tmp) / "alignment.patch"
        file.write_bytes(patch)
        result = subprocess.run(["git", "apply", "--numstat", "-z", str(file)], capture_output=True, cwd=ROOT)
    if result.returncode != 0:
        return [f"not a patch: {result.stderr.decode(errors='replace').strip()}"]
    fields = result.stdout.split(b"\0")
    paths: list[str] = []
    index = 0
    while index < len(fields) and fields[index]:
        head = fields[index].decode(errors="replace")
        if head.endswith("\t"):  # rename or copy: "added TAB deleted TAB", then the old and the new path
            paths += [fields[index + 1].decode(errors="replace"), fields[index + 2].decode(errors="replace")]
            index += 3
        else:
            paths.append(head.split("\t", 2)[2])
            index += 1
    problems = [f"{path}: not one of the files the update may change" for path in dict.fromkeys(paths)
                if path not in ALLOWED_PATHS]
    for line in patch.decode(errors="replace").splitlines():
        if line.startswith(HEADER_REFUSED) or (line.startswith("new file mode") and line != "new file mode 100644"):
            problems.append(f"patch header {line!r}: only regular files, edited or created in place")
    return problems


def verify_patch(path: Path) -> int:
    problems = patch_problems(path.read_bytes())
    for problem in problems:
        print(f"::error::{problem}" if os.environ.get("GITHUB_ACTIONS") else f"FAIL {problem}")
    if problems:
        print("The update changed more than the files it may change: " + ", ".join(ALLOWED_PATHS), file=sys.stderr)
        return 1
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    for command in ("check", "update"):
        p = sub.add_parser(command)
        p.add_argument("--web", type=Path, required=True, help="clone of HouseCairn/housecairn")
        if command == "update":
            p.add_argument("--release", required=True, help="release tag of the web application, vX.Y.Z")
            p.add_argument("--report", type=Path, help="write the Markdown report there")
    verify = sub.add_parser("verify-patch", help="refuse a patch that touches a file outside ALLOWED_PATHS")
    verify.add_argument("patch", type=Path)
    sub.add_parser("allowed-paths", help="print the files the update may change, one per line")
    args = parser.parse_args()
    try:
        if args.command == "verify-patch":
            return verify_patch(args.patch)
        if args.command == "allowed-paths":
            print("\n".join(ALLOWED_PATHS))
            return 0
        if args.command == "check":
            return check(args.web)
        return update(args.web, args.release, args.report)
    except AlignmentError as error:
        print(f"web_alignment: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
